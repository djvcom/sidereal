//! Background compaction of flushed files.
//!
//! Every flush writes a new small file, so the number of files a query has
//! to open grows with time. Compaction merges the files of an hour
//! partition into fewer, larger ones in the signal's sort order.
//!
//! # Levels
//!
//! A file's level is part of its name, so it can be read from a listing:
//!
//! - level 0, `{ulid}.parquet`: written by a flush
//! - level 1, `{id}-{n}.l1.parquet`: a merge of level 0 files, made while
//!   the partition is still receiving data
//! - level 2, `{id}-{n}.l2.parquet`: the final form, made once the
//!   partition has gone quiet
//!
//! Merging in two stages means each row is rewritten about twice, rather
//! than every time a partition gains a few more files.
//!
//! # Safety
//!
//! Replacing files must never show a query the same rows twice, nor lose
//! them, whatever fails and whenever. The bucket is the only durable state,
//! so the protocol is written into it as a small marker object beside the
//! data:
//!
//! 1. Write a marker naming the inputs, in state `writing`.
//! 2. Write the outputs. Their names start with the marker's ID.
//! 3. Rewrite the marker in state `committed`, naming the outputs. This
//!    single write is the commit point.
//! 4. Swap inputs for outputs in the in-memory catalogue, in one step.
//! 5. Delete the inputs, then the marker.
//!
//! A reader of the bucket (a restart, a refresh) applies two rules: files
//! belonging to a `writing` marker are ignored, and the inputs of a
//! `committed` marker are ignored. Whichever step a crash interrupts, the
//! rules yield either the inputs or the outputs, never both, and
//! [`Compactor::recover`] finishes or undoes the leftover work.
//!
//! Markers live for seconds and are younger than the inputs they name, so
//! a bucket lifecycle rule cannot expire one before its inputs.

