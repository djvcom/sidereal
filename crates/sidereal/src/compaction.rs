/// Suffix of compaction marker objects.
pub const MARKER_SUFFIX: &str = ".compaction.json";

/// Internal URL the compactor's own query context reads inputs through.
const COMPACTION_URL: &str = "sidereal://compaction";

/// Parallelism of a merge. Kept low so compaction leaves the processor to
/// ingestion and queries.
const MERGE_PARTITIONS: usize = 2;

/// Level of the final, settled form of a partition's files.
const FINAL_LEVEL: u8 = 2;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
enum MarkerState {
    /// Outputs are being written; they must not be read.
    Writing,
    /// Outputs are complete; the inputs must not be read.
    Committed,
}

/// The durable record of one compaction, stored beside the data.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct Marker {
    id: String,
    state: MarkerState,
    inputs: Vec<String>,
    outputs: Vec<String>,
}

/// The directory an object is in.
fn parent(path: &Path) -> Path {
    let mut parts: Vec<_> = path.parts().collect();
    parts.pop();
    Path::from_iter(parts)
}

/// Compaction level encoded in a data file's name, or `None` if the object
/// is not a data file.
fn level_of(path: &Path) -> Option<u8> {
    // Names are generated by Sidereal, always in this exact case.
    let stem = path.filename()?.strip_suffix(".parquet")?;
    match stem.rsplit_once('.') {
        Some((_, "l1")) => Some(1),
        Some((_, "l2")) => Some(2),
        _ => Some(0),
    }
}

fn is_marker(path: &Path) -> bool {
    path.filename()
        .is_some_and(|name| name.ends_with(MARKER_SUFFIX))
}

/// Whether `path` is an output of the compaction with this ID in
/// `partition`.
fn is_output_of(path: &Path, partition: &Path, id: &str) -> bool {
    parent(path) == *partition
        && path
            .filename()
            .is_some_and(|name| name.starts_with(&format!("{id}-")))
}

async fn read_marker(store: &dyn ObjectStore, path: &Path) -> Option<Marker> {
    let bytes = match store.get(path).await {
        Ok(result) => result.bytes().await.ok()?,
        Err(object_store::Error::NotFound { .. }) => return None,
        Err(error) => {
            tracing::warn!(%path, %error, "Could not read compaction marker");
            return None;
        }
    };
    match serde_json::from_slice(&bytes) {
        Ok(marker) => Some(marker),
        Err(error) => {
            tracing::warn!(%path, %error, "Ignoring unreadable compaction marker");
            None
        }
    }
}

/// Objects in `listed` that must not be visible because a compaction
/// marker says so: the outputs of a compaction still being written, and
/// the inputs of one that has committed.
///
/// Markers themselves stay visible so that recovery can find them.
pub(crate) async fn hidden_by_markers(
    store: &dyn ObjectStore,
    listed: &[ObjectMeta],
) -> HashSet<Path> {
    let mut hidden = HashSet::new();
    for meta in listed.iter().filter(|meta| is_marker(&meta.location)) {
        let Some(marker) = read_marker(store, &meta.location).await else {
            continue;
        };
        let partition = parent(&meta.location);
        match marker.state {
            MarkerState::Writing => hidden.extend(
                listed
                    .iter()
                    .filter(|other| is_output_of(&other.location, &partition, &marker.id))
                    .map(|other| other.location.clone()),
            ),
            MarkerState::Committed => {
                hidden.extend(marker.inputs.iter().map(|input| Path::from(input.as_str())));
            }
        }
    }
    hidden
}

/// One planned merge.
#[derive(Debug, Clone)]
pub struct Job {
    /// The hour partition whose files are merged.
    pub partition: Path,
    /// The signal the partition belongs to.
    pub signal: Signal,
    /// Files to merge.
    pub inputs: Vec<ObjectMeta>,
    /// Level of the files the merge produces.
    pub level: u8,
}

fn signal_of(partition: &Path) -> Option<Signal> {
    let first = partition.parts().next()?;
    [Signal::Traces, Signal::Metrics, Signal::Logs]
        .into_iter()
        .find(|signal| signal.as_str() == first.as_ref())
}

/// Decide which partitions to compact, given everything in the catalogue.
///
/// A partition that has gone `settle_secs` without a new file is merged
/// into its final form if more than one of its files is still below the
/// target size. A partition still receiving data has its freshly flushed
/// files merged whenever `minor_files` of them have accumulated, leaving
/// earlier merges alone.
#[must_use]
pub fn plan(objects: &[ObjectMeta], now: DateTime<Utc>, config: &CompactionConfig) -> Vec<Job> {
    let mut partitions: BTreeMap<Path, Vec<(&ObjectMeta, u8)>> = BTreeMap::new();
    for meta in objects {
        if let Some(level) = level_of(&meta.location) {
            partitions
                .entry(parent(&meta.location))
                .or_default()
                .push((meta, level));
        }
    }

    let settle = chrono::Duration::seconds(i64::try_from(config.settle_secs).unwrap_or(i64::MAX));
    let mut jobs = Vec::new();

    for (partition, files) in partitions {
        // Only hour partitions: {signal}/date=.../hour=...
        let Some(signal) = signal_of(&partition) else {
            continue;
        };
        if partition.parts().count() < 3 {
            continue;
        }

        let newest = files.iter().map(|(meta, _)| meta.last_modified).max();
        let settled = newest.is_some_and(|newest| now.signed_duration_since(newest) >= settle);

        let job = |inputs: Vec<&ObjectMeta>, level: u8| Job {
            partition: partition.clone(),
            signal,
            inputs: inputs.into_iter().cloned().collect(),
            level,
        };

        if settled {
            let unfinished: Vec<&ObjectMeta> = files
                .iter()
                .filter(|(meta, level)| {
                    *level < FINAL_LEVEL || meta.size < config.target_file_bytes / 2
                })
                .map(|(meta, _)| *meta)
                .collect();
            // A lone unfinished file is left as it is: rewriting it alone
            // would gain nothing.
            if unfinished.len() >= 2 {
                jobs.push(job(unfinished, FINAL_LEVEL));
            }
        } else {
            let flushed: Vec<&ObjectMeta> = files
                .iter()
                .filter(|(_, level)| *level == 0)
                .map(|(meta, _)| *meta)
                .collect();
            if flushed.len() >= config.minor_files.max(2) {
                jobs.push(job(flushed, 1));
            }
        }
    }
    jobs
}

/// What one compaction pass did.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct CompactionReport {
    /// Merges completed.
    pub jobs: usize,
    /// Files merged away.
    pub files_in: usize,
    /// Files written.
    pub files_out: usize,
    /// Rows rewritten.
    pub rows: usize,
    /// Merges that failed or were abandoned; their inputs are untouched.
    pub failed: usize,
    /// Interrupted compactions from an earlier run that were finished or
    /// undone.
    pub recovered: usize,
}

/// Merges small files into large ones.
pub struct Compactor {
    catalogue: Arc<CatalogueStore>,
    config: CompactionConfig,
    parquet: ParquetConfig,
    /// Partitions whose last merge failed, skipped until restart so a
    /// persistent problem is not retried every pass.
    failed: Mutex<HashSet<Path>>,
}

impl Compactor {
    /// Create a compactor over a catalogued store.
    #[must_use]
    pub fn new(
        catalogue: Arc<CatalogueStore>,
        config: CompactionConfig,
        parquet: ParquetConfig,
    ) -> Self {
        Self {
            catalogue,
            config,
            parquet,
            failed: Mutex::new(HashSet::new()),
        }
    }

    /// Finish or undo compactions that an earlier run left unfinished.
    ///
    /// Returns the number of markers dealt with.
    ///
    /// # Errors
    ///
    /// Returns an error if storage fails while cleaning up; the marker is
    /// left in place and recovery is attempted again on the next pass.
    pub async fn recover(&self) -> Result<usize, TelemetryError> {
        let _guard = self.catalogue.maintenance().await;
        self.recover_locked().await
    }

    async fn recover_locked(&self) -> Result<usize, TelemetryError> {
        let store = self.catalogue.inner();
        let markers: Vec<Path> = self
            .catalogue
            .objects(None)
            .into_iter()
            .map(|meta| meta.location)
            .filter(is_marker)
            .collect();

        let mut recovered = 0;
        for marker_path in markers {
            let partition = parent(&marker_path);
            match read_marker(store.as_ref(), &marker_path).await {
                Some(marker) if marker.state == MarkerState::Committed => {
                    let inputs: Vec<Path> = marker
                        .inputs
                        .iter()
                        .map(|input| Path::from(input.as_str()))
                        .collect();
                    self.catalogue.forget_all(&inputs);
                    delete_all(store.as_ref(), &inputs).await?;
                    tracing::info!(%partition, id = %marker.id, "Finished interrupted compaction");
                }
                Some(marker) => {
                    let outputs = self.outputs_in_storage(&partition, &marker.id).await?;
                    self.catalogue.forget_all(&outputs);
                    delete_all(store.as_ref(), &outputs).await?;
                    tracing::info!(%partition, id = %marker.id, "Discarded interrupted compaction");
                }
                None => {}
            }
            delete_all(store.as_ref(), std::slice::from_ref(&marker_path)).await?;
            self.catalogue
                .forget_all(std::slice::from_ref(&marker_path));
            recovered += 1;
        }
        Ok(recovered)
    }

    /// Outputs of compaction `id` that exist in storage, whether or not
    /// the catalogue knows about them.
    async fn outputs_in_storage(
        &self,
        partition: &Path,
        id: &str,
    ) -> Result<Vec<Path>, TelemetryError> {
        let store = self.catalogue.inner();
        let mut listing = store.list(Some(partition));
        let mut outputs = Vec::new();
        while let Some(meta) = listing.next().await {
            let meta = meta?;
            if is_output_of(&meta.location, partition, id) {
                outputs.push(meta.location);
            }
        }
        Ok(outputs)
    }

    /// Run one pass: recover leftovers, then merge every partition that is
    /// due.
    ///
    /// A failed merge is logged and counted, and leaves its inputs exactly
    /// as they were.
    ///
    /// # Errors
    ///
    /// Returns an error only if recovery fails.
    pub async fn run_once(&self) -> Result<CompactionReport, TelemetryError> {
        let _guard = self.catalogue.maintenance().await;
        let mut report = CompactionReport {
            recovered: self.recover_locked().await?,
            ..Default::default()
        };

        let jobs = plan(&self.catalogue.objects(None), Utc::now(), &self.config);
        for job in jobs {
            if self.lock_failed().contains(&job.partition) {
                continue;
            }
            match self.compact(&job).await {
                Ok((files_out, rows)) => {
                    report.jobs += 1;
                    report.files_in += job.inputs.len();
                    report.files_out += files_out;
                    report.rows += rows;
                    tracing::info!(
                        partition = %job.partition,
                        level = job.level,
                        files_in = job.inputs.len(),
                        files_out,
                        rows,
                        "Compacted partition"
                    );
                }
                Err(error) => {
                    report.failed += 1;
                    if self.forget_missing_inputs(&job).await {
                        // Inputs vanished underneath us (retention, or a
                        // bucket lifecycle rule). The next pass plans afresh.
                        tracing::info!(partition = %job.partition, "Compaction abandoned, inputs changed");
                    } else {
                        tracing::warn!(partition = %job.partition, %error, "Compaction failed, leaving files as they are");
                        self.lock_failed().insert(job.partition.clone());
                    }
                }
            }
        }
        Ok(report)
    }

    fn lock_failed(&self) -> std::sync::MutexGuard<'_, HashSet<Path>> {
        self.failed.lock().unwrap_or_else(PoisonError::into_inner)
    }

    /// Drop from the catalogue any of the job's inputs that no longer
    /// exist. Returns whether any were missing.
    async fn forget_missing_inputs(&self, job: &Job) -> bool {
        let store = self.catalogue.inner();
        let mut missing = Vec::new();
        for input in &job.inputs {
            if matches!(
                store.head(&input.location).await,
                Err(object_store::Error::NotFound { .. })
            ) {
                missing.push(input.location.clone());
            }
        }
        self.catalogue.forget_all(&missing);
        !missing.is_empty()
    }

    /// Merge one partition's inputs, following the protocol in the module
    /// documentation. Returns the number of files and rows written.
    async fn compact(&self, job: &Job) -> Result<(usize, usize), TelemetryError> {
        let store = self.catalogue.inner();
        let id = ulid::Ulid::new().to_string();
        let marker_path = job.partition.child(format!("{id}{MARKER_SUFFIX}"));
        let input_paths: Vec<Path> = job.inputs.iter().map(|m| m.location.clone()).collect();
        let mut marker = Marker {
            id: id.clone(),
            state: MarkerState::Writing,
            inputs: input_paths.iter().map(ToString::to_string).collect(),
            outputs: Vec::new(),
        };

        put_marker(store.as_ref(), &marker_path, &marker).await?;

        let written = self.write_outputs(job, &id).await;
        let (outputs, rows) = match written {
            Ok(written) => written,
            Err(error) => {
                self.discard(&job.partition, &id, &marker_path).await;
                return Err(error);
            }
        };

        marker.state = MarkerState::Committed;
        marker.outputs = outputs.iter().map(|m| m.location.to_string()).collect();
        if let Err(error) = put_marker(store.as_ref(), &marker_path, &marker).await {
            self.discard(&job.partition, &id, &marker_path).await;
            return Err(error);
        }

        // Committed. From here on the outputs are the truth; anything that
        // fails is finished by recovery on the next pass.
        let files_out = outputs.len();
        self.catalogue.replace(outputs, &input_paths);
        delete_all(store.as_ref(), &input_paths).await?;
        delete_all(store.as_ref(), std::slice::from_ref(&marker_path)).await?;
        Ok((files_out, rows))
    }

    /// Undo an uncommitted compaction: remove its outputs and its marker.
    /// Best effort; whatever is left is dealt with by recovery.
    async fn discard(&self, partition: &Path, id: &str, marker_path: &Path) {
        let store = self.catalogue.inner();
        let cleanup = async {
            let outputs = self.outputs_in_storage(partition, id).await?;
            delete_all(store.as_ref(), &outputs).await?;
            delete_all(store.as_ref(), std::slice::from_ref(marker_path)).await
        };
        if let Err(error) = cleanup.await {
            tracing::warn!(%partition, %error, "Could not clean up abandoned compaction; recovery will");
        }
    }

    /// Read the inputs in sort order and write them out as files of about
    /// the target size. Fails, writing nothing that will be kept, if the
    /// rows written do not match the rows read.
    async fn write_outputs(
        &self,
        job: &Job,
        id: &str,
    ) -> Result<(Vec<ObjectMeta>, usize), TelemetryError> {
        let store = self.catalogue.inner();
        let schema = storage_schema(job.signal);
        let layout = FileLayout::for_signal(job.signal);

        let runtime = RuntimeEnvBuilder::new()
            .with_memory_limit(self.config.memory_limit_bytes, 1.0)
            .build_arc()?;
        let state = SessionStateBuilder::new_with_default_features()
            .with_config(SessionConfig::new().with_target_partitions(MERGE_PARTITIONS))
            .with_runtime_env(runtime)
            .build();
        let ctx = SessionContext::from(state);
        let url = Url::parse(COMPACTION_URL).map_err(TelemetryError::UrlParse)?;
        ctx.register_object_store(&url, Arc::clone(&store));

        let urls: Vec<String> = job
            .inputs
            .iter()
            .map(|meta| format!("{COMPACTION_URL}/{}", meta.location))
            .collect();
        let options = ParquetReadOptions::default().schema(schema.as_ref());
        let mut frame = ctx.read_parquet(urls, options).await?;
        let rows_in = frame.clone().count().await?;

        let order: Vec<SortExpr> = layout
            .sort_columns
            .iter()
            .filter(|name| schema.index_of(name).is_ok())
            .map(|name| Expr::Column(Column::new_unqualified(*name)).sort(true, true))
            .collect();
        if !order.is_empty() {
            frame = frame.sort(order)?;
        }
        let mut stream = frame.execute_stream().await?;
        let out_schema: SchemaRef = stream.schema();

        // Distinct values per row group are not known while streaming; the
        // row count is a safe upper bound for sizing bloom filters.
        let rows_per_group =
            u64::try_from(rows_in.min(self.parquet.row_group_size).max(1)).unwrap_or(u64::MAX);
        let props = layout.properties(out_schema.as_ref(), &self.parquet, |_| rows_per_group);
        let target = usize::try_from(self.config.target_file_bytes).unwrap_or(usize::MAX);

        let mut paths: Vec<Path> = Vec::new();
        let mut rows_out: usize = 0;
        let mut open: Option<AsyncArrowWriter<ParquetObjectWriter>> = None;

        while let Some(batch) = stream.next().await {
            let batch = batch?;
            if batch.num_rows() == 0 {
                continue;
            }
            let mut writer = if let Some(writer) = open.take() {
                writer
            } else {
                let name = format!("{id}-{:03}.l{}.parquet", paths.len(), job.level);
                let path = job.partition.child(name);
                paths.push(path.clone());
                AsyncArrowWriter::try_new(
                    ParquetObjectWriter::new(Arc::clone(&store), path),
                    Arc::clone(&out_schema),
                    Some(props.clone()),
                )?
            };
            writer.write(&batch).await?;
            rows_out += batch.num_rows();

            if writer.bytes_written() + writer.in_progress_size() >= target {
                writer.close().await?;
            } else {
                open = Some(writer);
            }
        }
        if let Some(writer) = open {
            writer.close().await?;
        }

        if rows_out != rows_in {
            return Err(TelemetryError::Config(format!(
                "compaction of {} read {rows_in} rows but wrote {rows_out}",
                job.partition
            )));
        }

        let mut outputs = Vec::with_capacity(paths.len());
        for path in &paths {
            outputs.push(store.head(path).await?);
        }
        Ok((outputs, rows_out))
    }
}

fn storage_schema(signal: Signal) -> SchemaRef {
    match signal {
        Signal::Traces => traces_storage_schema(),
        Signal::Metrics => number_metrics_storage_schema(),
        Signal::Logs => logs_storage_schema(),
    }
}

async fn put_marker(
    store: &dyn ObjectStore,
    path: &Path,
    marker: &Marker,
) -> Result<(), TelemetryError> {
    let body = serde_json::to_vec(marker)
        .map_err(|e| TelemetryError::Config(format!("cannot encode compaction marker: {e}")))?;
    store.put(path, body.into()).await?;
    Ok(())
}

/// Delete objects, treating one that is already gone as deleted.
async fn delete_all(store: &dyn ObjectStore, paths: &[Path]) -> Result<(), TelemetryError> {
    for path in paths {
        match store.delete(path).await {
            Ok(()) | Err(object_store::Error::NotFound { .. }) => {}
            Err(error) => return Err(error.into()),
        }
    }
    Ok(())
}

/// Handle for the background compaction task.
pub struct CompactionHandle {
    shutdown_tx: Option<oneshot::Sender<()>>,
    join_handle: JoinHandle<()>,
}

impl CompactionHandle {
    /// Stop the background task and wait for the pass in progress, if any,
    /// to finish.
    pub async fn shutdown(mut self) {
        if let Some(tx) = self.shutdown_tx.take() {
            let _ = tx.send(());
        }
        let _ = self.join_handle.await;
    }
}

/// Run compaction passes at the configured interval.
pub fn start_background_compaction(compactor: Arc<Compactor>) -> CompactionHandle {
    let (shutdown_tx, mut shutdown_rx) = oneshot::channel();
    let interval = Duration::from_secs(compactor.config.interval_secs.max(1));

    let join_handle = tokio::spawn(async move {
        let mut ticker = tokio::time::interval(interval);
        ticker.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);

        loop {
            tokio::select! {
                _ = ticker.tick() => {
                    if let Err(error) = compactor.run_once().await {
                        tracing::warn!(%error, "Compaction pass failed");
                    }
                }
                _ = &mut shutdown_rx => break,
            }
        }
    });

    CompactionHandle {
        shutdown_tx: Some(shutdown_tx),
        join_handle,
    }
}

